/** Default UI language when settings/system do not override. */
export const DEFAULT_LANG: Lang = 'lt'

let current: Lang = DEFAULT_LANG

const supported: Lang[] = ['lt', 'en', 'ru', 'pt']

export function resolveLang(code: string | undefined | null): Lang {
  if (!code || code === 'system') {
    const nav = (navigator.language || DEFAULT_LANG).slice(0, 2).toLowerCase()
    if ((supported as string[]).includes(nav)) return nav as Lang
    return DEFAULT_LANG
  }
  const normalized = code.toLowerCase()
  if ((supported as string[]).includes(normalized)) return normalized as Lang
  return DEFAULT_LANG
}

export function setLang(code: string) {
  current = resolveLang(code)
}

export function t(key: string): string {
  return texts[current][key] || texts.lt[key] || texts.en[key] || key
}

export function currentLang(): Lang {
  return current
}
