import {
  CancelPlaylist,
  CheckForUpdates,
  ClearCompleted,
  ConfirmRestoreQueue,
  CopyLogs,
  CopySupportBundle,
  CopyToClipboard,
  DiscardRestoreQueue,
  GetLogPath,
  GetPlaylists,
  GetQualityHelp,
  GetRestoreInfo,
  GetSettings,
  GetTasks,
  GetClipboardText,
  GetVersion,
  HasPendingRestore,
  OpenDownloadFolder,
  OpenFile,
  PauseAll,
  ProbeMedia,
  RemoveTask,
  ResetSettings,
  RetryFailed,
  RetryTranscript,
  RevealFile,
  RevealLogFile,
  SaveSettings,
  SelectDownloadDirectory,
  StartDownload,
  StartDownloadRequest,
  TogglePause,
} from '../wailsjs/go/main/App'
import { EventsOn } from '../wailsjs/runtime/runtime'
import type {
  ActionResult,
  DownloadRequest,
  DownloadTask,
  MediaProbeResult,
  Playlist,
  QueueRestorePayload,
  SettingsData,
  UpdateCheckResult,
} from './types'

export const api = {
  getVersion: () => GetVersion(),
  getSettings: () => GetSettings() as Promise<SettingsData>,
  saveSettings: (data: SettingsData) => SaveSettings(data as never) as Promise<ActionResult>,
  resetSettings: () => ResetSettings() as Promise<ActionResult>,
  selectDownloadDirectory: () => SelectDownloadDirectory(),
  openDownloadFolder: () => OpenDownloadFolder() as Promise<ActionResult>,
  getTasks: () => GetTasks() as Promise<DownloadTask[]>,
  getPlaylists: () => GetPlaylists() as Promise<Playlist[]>,
  startDownload: (url: string) => StartDownload(url) as Promise<ActionResult>,
  startDownloadRequest: (req: DownloadRequest) =>
    StartDownloadRequest(req as never) as Promise<ActionResult>,
  probeMedia: (url: string) => ProbeMedia(url) as Promise<MediaProbeResult>,
  togglePause: (taskID: string) => TogglePause(taskID) as Promise<ActionResult>,
  removeTask: (taskID: string) => RemoveTask(taskID) as Promise<ActionResult>,
  openFile: (filePath: string) => OpenFile(filePath) as Promise<ActionResult>,
  revealFile: (filePath: string) => RevealFile(filePath) as Promise<ActionResult>,
  copyToClipboard: (text: string) => CopyToClipboard(text) as Promise<ActionResult>,
  getClipboardText: () => GetClipboardText() as Promise<ActionResult>,
  copyLogs: () => CopyLogs() as Promise<ActionResult>,
  copySupportBundle: () => CopySupportBundle() as Promise<ActionResult>,
  getLogPath: () => GetLogPath() as Promise<string>,
  revealLogFile: () => RevealLogFile() as Promise<ActionResult>,
  retryTranscript: (taskID: string) => RetryTranscript(taskID) as Promise<ActionResult>,
  cancelPlaylist: (playlistID: string) => CancelPlaylist(playlistID) as Promise<ActionResult>,
  pauseAll: () => PauseAll() as Promise<ActionResult>,
  clearCompleted: () => ClearCompleted() as Promise<ActionResult>,
  retryFailed: () => RetryFailed() as Promise<ActionResult>,
  confirmRestoreQueue: () => ConfirmRestoreQueue() as Promise<ActionResult>,
  discardRestoreQueue: () => DiscardRestoreQueue() as Promise<ActionResult>,
  hasPendingRestore: () => HasPendingRestore() as Promise<boolean>,
  getRestoreInfo: () => GetRestoreInfo() as Promise<QueueRestorePayload & { pending?: boolean }>,
  getQualityHelp: () => GetQualityHelp() as Promise<Record<string, string>>,
  checkForUpdates: () => CheckForUpdates() as Promise<UpdateCheckResult>,
}

export function eventsOn(event: string, callback: (...data: unknown[]) => void): () => void {
  return EventsOn(event, callback)
}
